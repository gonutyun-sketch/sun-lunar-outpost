import { dot, face, line, oval, random, type Point } from './pixels';

/** A quiet lunar horizon behind the outpost's information terminals. */
export function paintLunarBackdrop(g: CanvasRenderingContext2D) {
  const { width, height } = g.canvas;
  const rng = random(1382);
  dot(g, 0, 0, '#0a1121', width, height);
  dot(g, 0, 46, '#0c1527', width, height - 46);
  dot(g, 0, 108, '#111d31', width, height - 108);
  const starInk = ['#263951', '#3d536c', '#657f98', '#98a9bd'];
  for (let i = 0; i < 116; i++) {
    const x = rng() * width, y = rng() * 151, light = rng();
    dot(g, x, y, starInk[Math.floor(light * starInk.length)], light > 0.96 ? 2 : 1);
    if (light > 0.98) dot(g, x, y - 1, starInk[1], 1, 3);
  }

  oval(g, 353, 45, 17, 16, '#162944');
  oval(g, 354, 44, 14, 14, '#293e59');
  oval(g, 359, 44, 8, 12, '#4e6580');
  face(g, [[350, 32], [356, 29], [360, 31], [356, 34], [357, 38], [362, 39], [365, 44], [358, 43], [354, 38], [348, 38]], '#66848a');
  face(g, [[361, 46], [367, 46], [363, 53], [359, 56], [358, 53], [361, 51]], '#658181');

  const ridge: Point[] = [
    [-1, 156], [16, 148], [29, 149], [67, 123], [77, 121],
    [114, 144], [131, 137], [151, 146], [181, 152], [209, 147],
    [226, 151], [252, 132], [277, 125], [300, 134], [311, 132],
    [343, 118], [365, 122], [388, 136], [417, 129],
  ];
  face(g, [...ridge, [417, height], [-1, height]], '#202941');
  face(g, [[21, 151], [67, 123], [77, 121], [114, 144], [85, 137], [75, 146], [56, 142], [47, 151]], '#394051');
  face(g, [[308, 135], [343, 118], [365, 122], [388, 136], [361, 130], [346, 126], [336, 135]], '#343d52');
  face(g, [[0, 180], [52, 165], [108, 160], [161, 170], [202, 164], [257, 171], [301, 152], [351, 160], [416, 151], [416, height], [0, height]], '#161f33');
  face(g, [[0, 208], [42, 193], [87, 191], [139, 199], [194, 186], [235, 189], [276, 181], [345, 186], [416, 173], [416, height], [0, height]], '#111a2b');
  oval(g, 31, 216, 34, 7, '#0c1526');
  oval(g, 34, 213, 29, 5, '#242c40');
  oval(g, 32, 213, 27, 4, '#111a2b');
  oval(g, 331, 220, 18, 4, '#0d1628');
  for (let i = 0; i < 96; i++) {
    dot(g, rng() * width, 182 + rng() * (height - 182), i % 3 === 0 ? '#2b3347' : '#1d283c', i % 9 === 0 ? 3 : 1);
  }

  // A distant relay at the edge of the plain. Text panels stay in front of the dark centre.
  line(g, [384, 182], [375, 188], '#0a1323', 2);
  line(g, [384, 182], [384, 163], '#5c6574', 2);
  line(g, [384, 173], [391, 179], '#384658');
  face(g, [[377, 160], [380, 165], [386, 167], [392, 163], [393, 158], [390, 161], [383, 163]], '#6c7683');
  dot(g, 388, 162, '#81a4af', 2);
  dot(g, 380, 181, '#526073', 9, 2);
  dot(g, 389, 180, '#927e5c', 2);
}
